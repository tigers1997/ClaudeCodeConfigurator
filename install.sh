#!/usr/bin/env bash
# One-shot installer for cc-configure.
#
# Usage:
#   curl -sL https://raw.githubusercontent.com/tigers1997/ClaudeCodeConfigurator/main/install.sh | bash
# or after cloning:
#   ./install.sh [install-dir]
#
# What it does:
#   1. Clones the repo to ~/.cc-configurator (or $1 if given).
#   2. Symlinks configure.py into ~/.local/bin/cc-configure.
#   3. Ensures ~/.local/bin is on PATH (prints instructions if not).
#
# After install:
#   cd your-project && cc-configure
set -euo pipefail

INSTALL_DIR="${1:-$HOME/.cc-configurator}"
REPO_URL="https://github.com/tigers1997/ClaudeCodeConfigurator.git"
BIN_DIR="$HOME/.local/bin"
BIN_NAME="cc-configure"

if ! command -v git >/dev/null 2>&1; then
  echo "ERROR: git not found. Install it first, then re-run this installer." >&2
  exit 1
fi

echo "==> Installing cc-configure"
echo "    source   : $INSTALL_DIR"
echo "    shortcut : $BIN_DIR/$BIN_NAME"

# 1. Clone or update
if [ -d "$INSTALL_DIR/.git" ]; then
  echo "==> $INSTALL_DIR exists — pulling latest"
  git -C "$INSTALL_DIR" pull --ff-only
elif [ -e "$INSTALL_DIR" ]; then
  echo "ERROR: $INSTALL_DIR exists and is not a git clone. Refusing to overwrite." >&2
  exit 1
else
  echo "==> Cloning $REPO_URL"
  git clone --depth=1 "$REPO_URL" "$INSTALL_DIR"
fi

# 2. Ensure Python 3.8+
if ! command -v python3 >/dev/null 2>&1; then
  case "$(uname -s)" in
    Darwin)             hint="brew install python3" ;;
    MINGW*|MSYS*|CYGWIN*) hint="install Python from python.org, or: winget install Python.Python.3" ;;
    *)                  hint="apt install python3  (or your distro's equivalent)" ;;
  esac
  echo "ERROR: python3 not found. Install it first: $hint" >&2
  exit 1
fi
PY_VER=$(python3 -c 'import sys; print(".".join(map(str,sys.version_info[:2])))')
if [ "$(python3 -c 'import sys; print(sys.version_info >= (3,8))')" != "True" ]; then
  echo "ERROR: Python 3.8+ required (found $PY_VER)." >&2
  exit 1
fi

# 3. chmod configure.py + link (or shim)
chmod +x "$INSTALL_DIR/configure.py"
mkdir -p "$BIN_DIR"

# `ln -s` under Git Bash/MSYS silently COPIES unless MSYS=winsymlinks:nativestrict
# and the user has Developer Mode (or admin) — which turned the shortcut into a
# frozen snapshot: `git -C ~/.cc-configurator pull` updated the clone while
# cc-configure kept running the version installed on day one. Verify the link
# actually points somewhere and fall back to a two-line exec shim, which tracks
# the clone on every platform.
# Both conditions live in the `if` test: under `set -e`, a bare
# `[ -L … ] && link_ok=1` as the last statement of a then-block would abort
# the installer on exactly the platform this fallback exists for.
link_ok=0
if ln -sf "$INSTALL_DIR/configure.py" "$BIN_DIR/$BIN_NAME" 2>/dev/null \
   && [ -L "$BIN_DIR/$BIN_NAME" ]; then
  link_ok=1
fi

if [ "$link_ok" = "1" ]; then
  echo "==> Linked $BIN_DIR/$BIN_NAME -> $INSTALL_DIR/configure.py"
else
  rm -f "$BIN_DIR/$BIN_NAME"
  cat > "$BIN_DIR/$BIN_NAME" <<SHIM
#!/usr/bin/env bash
# Generated by the cc-configurator installer because this platform could not
# create a real symlink. Execs the clone, so \`git -C "$INSTALL_DIR" pull\`
# still updates what this command runs.
exec python3 "$INSTALL_DIR/configure.py" "\$@"
SHIM
  chmod +x "$BIN_DIR/$BIN_NAME"
  echo "==> Symlinks unavailable here; wrote an exec shim at $BIN_DIR/$BIN_NAME"
  echo "    (it runs $INSTALL_DIR/configure.py, so updates still apply)"
fi

# 4. PATH hint
if ! echo ":$PATH:" | grep -q ":$BIN_DIR:"; then
  echo ""
  echo "WARNING: $BIN_DIR is not on your PATH."
  echo "Add this line to your shell config (~/.bashrc, ~/.zshrc):"
  echo ""
  echo "    export PATH=\"\$HOME/.local/bin:\$PATH\""
  echo ""
  echo "Then: source ~/.bashrc  (or restart your shell)"
fi

echo ""
echo "==> Done."
echo ""
echo "Usage:"
echo "    cd your-project"
echo "    cc-configure                       # 5-question quick mode"
echo "    cc-configure --persona solo-newer --yes   # one-shot, no prompts"
echo "    cc-configure --detailed            # full intake"
echo "    cc-configure --help                # full options"
echo ""
echo "To update: re-run this installer, or:"
echo "    git -C $INSTALL_DIR pull"
